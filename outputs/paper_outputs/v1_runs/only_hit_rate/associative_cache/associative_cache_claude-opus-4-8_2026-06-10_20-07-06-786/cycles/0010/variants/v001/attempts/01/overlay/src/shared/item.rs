//! This module defines a key-value data object stored in the associative cache.
//!
//! # Examples
//!
//! ```ignore
//! use associative_cache::shared::item::Item;
//!
//! let item = Item::new(1, 2);
//! assert_eq!(item.key, 1);
//! assert_eq!(item.value, 2);
//! assert_eq!(item.lfu_counter, 0);
//! ```

use std::{
	fmt::{Display, Formatter},
	hash::Hash,
	sync::atomic::{AtomicU64, Ordering},
};

/// H01 (metadata): process-global monotonic logical clock backing item ages.
///
/// Replaces the per-item `Instant` timestamp with a single shared `AtomicU64`
/// tick counter. Each call to [`next_timestamp`] returns a strictly increasing
/// value, so "smaller timestamp == older item" holds exactly as it did with
/// `Instant` (which orders by wall-clock creation/refresh time). This shrinks
/// `Item<u64, u64>` from 40 to 32 bytes by storing an 8-byte `u64` instead of a
/// 16-byte `Instant`, without changing any victim/promotion ordering decision.
static LOGICAL_CLOCK: AtomicU64 = AtomicU64::new(0);

/// Returns the next monotonically increasing logical tick. Bumped at exactly the
/// sites the old `Instant::now()` was read (item creation and the get-path
/// timestamp refresh), preserving the total age order (smaller == older).
pub fn next_timestamp() -> u64 {
	LOGICAL_CLOCK.fetch_add(1, Ordering::Relaxed)
}

#[derive(Debug, Clone)]
pub struct Item<K, V>
where
	K: Hash + Eq + Clone,
	V: Eq + Clone,
{
	pub key: K,
	pub value: V,
	pub lfu_counter: usize,
	pub timestamp: u64,
}

impl<K, V> Item<K, V>
where
	K: Hash + Eq + Clone,
	V: Eq + Clone,
{
	pub fn new(key: K, value: V) -> Self {
		Self {
			key,
			value,
			lfu_counter: 0,
			timestamp: next_timestamp(),
		}
	}
}

impl<K, V> PartialEq for Item<K, V>
where
	K: Hash + Eq + Clone,
	V: Eq + Clone,
{
	fn eq(&self, other: &Item<K, V>) -> bool {
		self.key == other.key && self.value == other.value
	}
}

impl<K, V> Eq for Item<K, V>
where
	K: Hash + Eq + Clone,
	V: Eq + Clone,
{
}

impl<K, V> Display for Item<K, V>
where
	K: Hash + Eq + Clone + Display,
	V: Eq + Clone + Display,
{
	fn fmt(&self, f: &mut Formatter<'_>) -> std::fmt::Result {
		write!(
			f,
			"Bucket Item {{ key: {}, value: {}, lfu_counter: {}, timestamp: {:?} }}",
			self.key, self.value, self.lfu_counter, self.timestamp
		)
	}
}

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn new_initializes_fields() {
		let item = Item::new(42, "hello");
		assert_eq!(item.key, 42);
		assert_eq!(item.value, "hello");
		assert_eq!(item.lfu_counter, 0);
	}

	#[test]
	fn equality_compares_key_and_value() {
		let a = Item::new(1, 10);
		let b = Item::new(1, 10);
		let c = Item::new(1, 20);
		let d = Item::new(2, 10);

		assert_eq!(a, b);
		assert_ne!(a, c); // different value
		assert_ne!(a, d); // different key
	}

	#[test]
	fn equality_ignores_lfu_counter() {
		let mut a = Item::new(1, 10);
		let b = Item::new(1, 10);
		a.lfu_counter = 99;
		assert_eq!(a, b);
	}

	#[test]
	fn clone_produces_independent_copy() {
		let mut a = Item::new(1, 10);
		let b = a.clone();
		a.value = 20;
		assert_eq!(a.value, 20);
		assert_eq!(b.value, 10);
	}
}
